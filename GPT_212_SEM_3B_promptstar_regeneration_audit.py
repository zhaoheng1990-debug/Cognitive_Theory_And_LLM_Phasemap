def align_feature_spaces(original_features: pd.DataFrame, promptstar_features: pd.DataFrame, block: str):
    cols_orig = set(get_feature_cols(original_features, block))
    cols_ps = set(get_feature_cols(promptstar_features, block))
    cols = sorted(cols_orig & cols_ps)
    if not cols:
        return None, None, []

    combined = pd.concat(
        [
            original_features[cols].replace([np.inf, -np.inf], np.nan).fillna(0.0),
            promptstar_features[cols].replace([np.inf, -np.inf], np.nan).fillna(0.0),
        ],
        axis=0,
    )
    scaler = StandardScaler()
    scaler.fit(combined.values.astype(np.float32))

    Xo = scaler.transform(original_features[cols].replace([np.inf, -np.inf], np.nan).fillna(0.0).values.astype(np.float32))
    Xp = scaler.transform(promptstar_features[cols].replace([np.inf, -np.inf], np.nan).fillna(0.0).values.astype(np.float32))
    return Xo, Xp, cols


def compare_regeneration(original_features: pd.DataFrame, promptstar_features: pd.DataFrame, block: str):
    Xo, Xp, cols = align_feature_spaces(original_features, promptstar_features, block)
    if Xo is None:
        return pd.DataFrame()

    orig = original_features.reset_index(drop=True)
    ps = promptstar_features.reset_index(drop=True)

    # Candidate maps.
    ps_by_family_type = {}
    for i, row in ps.iterrows():
        ps_by_family_type[(row["seed_family"], row["template_type"])] = i

    ps_indices_by_family = {}
    for i, row in ps.iterrows():
        ps_indices_by_family.setdefault(row["seed_family"], []).append(i)

    all_ps_indices = list(range(len(ps)))

    rows = []
    for oi, row in orig.iterrows():
        if row.get("row_type") != "original_prompt":
            continue
        true_family = row["seed_family"]
        x = Xo[oi]

        for template_type in cfg.TEMPLATE_TYPES:
            key = (true_family, template_type)
            if key not in ps_by_family_type:
                continue

            same_idx = ps_by_family_type[key]
            xsame = Xp[same_idx]

            # Same-family promptstar similarity.
            same_cos = cosine_np(x, xsame)
            same_l2 = float(np.linalg.norm(x - xsame))

            # Random-family baseline: all promptstars with same template_type but different family.
            rand_idxs = [
                i for i, pr in ps.iterrows()
                if pr["template_type"] == template_type and pr["seed_family"] != true_family
            ]
            if rand_idxs:
                rand_cos = np.array([cosine_np(x, Xp[i]) for i in rand_idxs])
                rand_l2 = np.array([np.linalg.norm(x - Xp[i]) for i in rand_idxs])
                rand_mean_cos = float(np.mean(rand_cos))
                rand_max_cos = float(np.max(rand_cos))
                rand_mean_l2 = float(np.mean(rand_l2))
                rand_min_l2 = float(np.min(rand_l2))
            else:
                rand_mean_cos = rand_max_cos = rand_mean_l2 = rand_min_l2 = np.nan

            # Nearest Prompt* among all candidates.
            all_cos = np.array([cosine_np(x, Xp[i]) for i in all_ps_indices])
            nn_idx = int(np.argmax(all_cos))
            nn_family = ps.iloc[nn_idx]["seed_family"]
            nn_template_type = ps.iloc[nn_idx]["template_type"]

            rows.append({
                "row_id": int(row["row_id"]),
                "block": block,
                "template_type": template_type,
                "true_family": true_family,
                "original_prompt": row["prompt"],
                "promptstar_prompt": ps.iloc[same_idx]["prompt"],
                "same_family_cos": same_cos,
                "same_family_l2": same_l2,
                "random_family_mean_cos": rand_mean_cos,
                "random_family_max_cos": rand_max_cos,
                "random_family_mean_l2": rand_mean_l2,
                "random_family_min_l2": rand_min_l2,
                "cos_margin_vs_random_mean": same_cos - rand_mean_cos if np.isfinite(rand_mean_cos) else np.nan,
                "cos_margin_vs_random_max": same_cos - rand_max_cos if np.isfinite(rand_max_cos) else np.nan,
                "l2_gain_vs_random_mean": rand_mean_l2 - same_l2 if np.isfinite(rand_mean_l2) else np.nan,
                "l2_gain_vs_random_min": rand_min_l2 - same_l2 if np.isfinite(rand_min_l2) else np.nan,
                "nearest_promptstar_family": nn_family,
                "nearest_promptstar_template_type": nn_template_type,
                "nearest_promptstar_correct_family": int(nn_family == true_family),
                "n_features": len(cols),
            })

    return pd.DataFrame(rows)


