def main():
    set_seed(cfg.RANDOM_SEED)
    outdir = Path(cfg.OUTPUT_DIR)
    ensure_dir(str(outdir))
    json_dump(asdict(cfg), outdir / "sem3b_config.json")

    sem3a_dataset, sem3a_features, prompt_candidates, promptstar_dataset = load_inputs(cfg)
    promptstar_dataset.to_csv(outdir / "sem3b_promptstar_dataset.csv", index=False, encoding="utf-8-sig")

    ps_feat_path = outdir / "sem3b_promptstar_features.csv"
    if cfg.REUSE_PROMPTSTAR_FEATURES_IF_EXISTS and ps_feat_path.exists():
        print(f"[SEM-3B] Reusing Prompt* features: {ps_feat_path}")
        promptstar_features = pd.read_csv(ps_feat_path)
    else:
        model, tokenizer = load_model_and_tokenizer(cfg)
        promptstar_features = extract_all_features(promptstar_dataset, model, tokenizer, cfg)
        promptstar_features.to_csv(ps_feat_path, index=False, encoding="utf-8-sig")
        print(f"[SEM-3B] Prompt* features saved: {ps_feat_path}")

    # Compare only original prompt rows from SEM-3A.
    original_features = sem3a_features[sem3a_features["row_type"] == "original_prompt"].copy()

    blocks = ["center_pca", "decision", "mid", "all", "scalar", "transport", "init"]
    pairwise = []
    for block in blocks:
        print(f"[SEM-3B] Comparing block={block}")
        dfb = compare_regeneration(original_features, promptstar_features, block)
        if len(dfb):
            pairwise.append(dfb)

    pair_df = pd.concat(pairwise, ignore_index=True) if pairwise else pd.DataFrame()
    pair_df.to_csv(outdir / "sem3b_pairwise_regeneration.csv", index=False, encoding="utf-8-sig")

    fam_df = family_summary(pair_df) if len(pair_df) else pd.DataFrame()
    fam_df.to_csv(outdir / "sem3b_family_summary.csv", index=False, encoding="utf-8-sig")

    template_df = summarize_pairwise(pair_df) if len(pair_df) else pd.DataFrame()
    template_df.to_csv(outdir / "sem3b_template_type_summary.csv", index=False, encoding="utf-8-sig")

    stats_df = statistical_tests(pair_df) if len(pair_df) else pd.DataFrame()
    stats_df.to_csv(outdir / "sem3b_statistical_tests.csv", index=False, encoding="utf-8-sig")

    summary = build_results_summary(template_df, stats_df)
    json_dump(summary, outdir / "sem3b_results_summary.json")

    print("=" * 100)
    print("SEM-3B: Prompt*(mu_F) Regeneration Audit")
    print("=" * 100)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print("\nOutput files:")
    for p in [
        "sem3b_config.json",
        "sem3b_promptstar_dataset.csv",
        "sem3b_promptstar_features.csv",
        "sem3b_pairwise_regeneration.csv",
        "sem3b_family_summary.csv",
        "sem3b_template_type_summary.csv",
        "sem3b_statistical_tests.csv",
        "sem3b_results_summary.json",
    ]:
        print("  -", outdir / p)


if __name__ == "__main__":
    main()
