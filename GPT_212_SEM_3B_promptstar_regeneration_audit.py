def statistical_tests(pair_df: pd.DataFrame):
    rows = []
    for (block, template_type), g in pair_df.groupby(["block", "template_type"]):
        cos_same = g["same_family_cos"].values
        cos_rand = g["random_family_mean_cos"].values
        l2_same = g["same_family_l2"].values
        l2_rand = g["random_family_mean_l2"].values

        # paired t and Wilcoxon for cos margin and l2 gain.
        try:
            t_cos = ttest_rel(cos_same, cos_rand, nan_policy="omit")
            t_cos_stat, t_cos_p = float(t_cos.statistic), float(t_cos.pvalue)
        except Exception:
            t_cos_stat, t_cos_p = np.nan, np.nan
        try:
            w_cos = wilcoxon(cos_same - cos_rand)
            w_cos_stat, w_cos_p = float(w_cos.statistic), float(w_cos.pvalue)
        except Exception:
            w_cos_stat, w_cos_p = np.nan, np.nan

        try:
            t_l2 = ttest_rel(l2_rand, l2_same, nan_policy="omit")  # rand - same > 0
            t_l2_stat, t_l2_p = float(t_l2.statistic), float(t_l2.pvalue)
        except Exception:
            t_l2_stat, t_l2_p = np.nan, np.nan
        try:
            w_l2 = wilcoxon(l2_rand - l2_same)
            w_l2_stat, w_l2_p = float(w_l2.statistic), float(w_l2.pvalue)
        except Exception:
            w_l2_stat, w_l2_p = np.nan, np.nan

        rows.append({
            "block": block,
            "template_type": template_type,
            "n": int(len(g)),
            "cos_margin_mean": float(np.nanmean(cos_same - cos_rand)),
            "cos_paired_t_stat": t_cos_stat,
            "cos_paired_t_p": t_cos_p,
            "cos_wilcoxon_stat": w_cos_stat,
            "cos_wilcoxon_p": w_cos_p,
            "l2_gain_mean": float(np.nanmean(l2_rand - l2_same)),
            "l2_paired_t_stat": t_l2_stat,
            "l2_paired_t_p": t_l2_p,
            "l2_wilcoxon_stat": w_l2_stat,
            "l2_wilcoxon_p": w_l2_p,
        })
    return pd.DataFrame(rows)


def build_results_summary(pair_summary: pd.DataFrame, stats_df: pd.DataFrame):
    summary = {
        "config": asdict(cfg),
        "verdict": "UNDETERMINED",
        "best": {},
        "main_block": cfg.MAIN_BLOCK,
        "interpretation": [],
    }

    if len(pair_summary):
        # Main score prioritizes same-family cosine margin, fraction gt random, and NN correct.
        ps = pair_summary.copy()
        ps["score"] = (
            ps["mean_cos_margin_vs_random_mean"].fillna(-999)
            + ps["frac_cos_gt_random_mean"].fillna(0)
            + ps["nearest_promptstar_correct_family_rate"].fillna(0)
        )
        best = ps.sort_values("score", ascending=False).iloc[0].to_dict()
        summary["best"] = best

        main_candidates = ps[ps["block"] == cfg.MAIN_BLOCK]
        if len(main_candidates):
            main_best = main_candidates.sort_values("score", ascending=False).iloc[0].to_dict()
            summary["main_block_best"] = main_best

    # Verdict logic.
    best = summary.get("main_block_best", summary.get("best", {}))
    margin = best.get("mean_cos_margin_vs_random_mean", -999)
    frac = best.get("frac_cos_gt_random_mean", 0)
    nn = best.get("nearest_promptstar_correct_family_rate", 0)
    l2_gain = best.get("mean_l2_gain_vs_random_mean", -999)

    if margin > 0 and frac >= 0.85 and nn >= 0.70 and l2_gain > 0:
        summary["verdict"] = "PASS_STRONG_PROMPTSTAR_REGENERATION"
    elif margin > 0 and frac >= 0.70 and nn >= 0.50:
        summary["verdict"] = "PASS_LITE_PROMPTSTAR_REGENERATION"
    elif margin > 0 and frac >= 0.60:
        summary["verdict"] = "PARTIAL_PASS_PROMPTSTAR_SIGNAL"
    else:
        summary["verdict"] = "NO_PASS_YET"

    summary["interpretation"] = [
        "This tests regenerated Prompt* candidates, not exact original prompt inversion.",
        "A positive result means Prompt*(mu_F) trajectories are closer to original prompt trajectories than random-family Prompt*.",
        "template_type comparison identifies whether natural, structured, or compressed Prompt* best represents the family center.",
        "The next step after PASS is to compare Prompt* against hand-written canonical seed directly using the same feature extractor.",
    ]
    return summary


