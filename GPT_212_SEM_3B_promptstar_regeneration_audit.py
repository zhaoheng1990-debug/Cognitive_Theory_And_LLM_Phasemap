def build_promptstar_dataset(prompt_candidates: pd.DataFrame, cfg: CFG):
    rows = []
    for _, r in prompt_candidates.iterrows():
        if r["template_type"] not in cfg.TEMPLATE_TYPES:
            continue
        rows.append({
            "row_id": len(rows),
            "row_type": "prompt_star",
            "seed_family": r["seed_family"],
            "template_type": r["template_type"],
            "concept_star": r.get("concept_star", ""),
            "operator_id": r.get("operator_id", ""),
            "common_structure": r.get("common_structure", ""),
            "prompt": r["prompt_star_candidate"],
        })
    return pd.DataFrame(rows)


