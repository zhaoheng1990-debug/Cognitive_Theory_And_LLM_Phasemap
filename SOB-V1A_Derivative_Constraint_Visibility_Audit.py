def now_time():
    return time.strftime("%Y-%m-%d %H:%M:%S")


def safe_float(x, default=np.nan):
    try:
        if x is None:
            return default
        if isinstance(x, (float, int, np.floating, np.integer)):
            return float(x)
        return float(str(x))
    except Exception:
        return default


def safe_mean(xs):
    arr = np.asarray([safe_float(x) for x in xs], dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return np.nan
    return float(arr.mean())


def normalize_text(s):
    s = str(s).lower()
    s = s.replace("’", "'").replace("“", '"').replace("”", '"')
    return s


def count_words(s):
    return len(re.findall(r"\b[\w'-]+\b", str(s)))


def marker_score(text, markers):
    t = normalize_text(text)
    if not markers:
        return 0.0, 0, []
    hits = []
    for m in markers:
        if normalize_text(m) in t:
            hits.append(m)
    score = len(set(hits)) / max(1, len(markers))
    return float(min(1.0, score)), len(set(hits)), sorted(set(hits))


def lexical_diversity(text):
    words = re.findall(r"\b[a-zA-Z][a-zA-Z'-]*\b", normalize_text(text))
    if not words:
        return 0.0
    return float(len(set(words)) / max(1, len(words)))


def compression_bonus(text):
    n = count_words(text)
    if n <= 0:
        return 0.0
    if 35 <= n <= 120:
        return 1.0
    if n < 35:
        return max(0.0, n / 35.0)
    return max(0.0, 1.0 - (n - 120) / 260.0)


def overclaim_penalty(text, state_id):
    t = normalize_text(text)
    markers = NEGATIVE_MARKERS.get(state_id, [])
    hits = [m for m in markers if normalize_text(m) in t]
    if not hits:
        return 0.0, []
    return min(0.35, 0.08 * len(set(hits))), sorted(set(hits))


def score_answer(row):
    text = row.get("answer_text", "")
    dim = row.get("dimension", "")
    state_id = row.get("state_id", "")

    base, hit_count, hits = marker_score(text, EXPECTED_MARKERS.get(dim, []))
    word_n = count_words(text)
    div = lexical_diversity(text)
    cb = compression_bonus(text) if dim == "CP" else 0.0
    penalty, penalty_hits = overclaim_penalty(text, state_id)

    length_quality = 0.0
    if word_n > 10:
        length_quality = min(1.0, math.log1p(word_n) / math.log1p(120))

    if dim == "CP":
        score = 0.68 * base + 0.22 * cb + 0.10 * div
    else:
        score = 0.78 * base + 0.12 * length_quality + 0.10 * div

    score = max(0.0, min(1.0, score - penalty))

    return {
        "rubric_score": score,
        "marker_score": base,
        "marker_hit_count": hit_count,
        "marker_hits": "; ".join(hits),
        "word_count": word_n,
        "lexical_diversity": div,
        "compression_bonus": cb,
        "overclaim_penalty": penalty,
        "overclaim_hits": "; ".join(penalty_hits),
    }


