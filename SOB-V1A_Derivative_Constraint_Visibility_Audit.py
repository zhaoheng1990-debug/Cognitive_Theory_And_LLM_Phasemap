def format_chat(tokenizer, prompt):
    if hasattr(tokenizer, "apply_chat_template") and tokenizer.chat_template:
        try:
            return tokenizer.apply_chat_template(
                [{"role": "user", "content": prompt}],
                tokenize=False,
                add_generation_prompt=True,
            )
        except Exception:
            return prompt
    return prompt


def load_model_and_tokenizer(path, trust_remote_code=True):
    tokenizer = AutoTokenizer.from_pretrained(
        path,
        trust_remote_code=trust_remote_code,
        local_files_only=True,
    )
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        path,
        trust_remote_code=trust_remote_code,
        local_files_only=True,
        torch_dtype=DTYPE,
        device_map=None,
    )
    model.to(DEVICE)
    model.eval()
    return model, tokenizer


@torch.no_grad()
def generate_answer(model, tokenizer, prompt):
    text = format_chat(tokenizer, prompt)
    enc = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=MAX_INPUT_LEN,
    )
    enc = {k: v.to(DEVICE) for k, v in enc.items()}

    gen_kwargs = {
        "max_new_tokens": MAX_NEW_TOKENS,
        "do_sample": DO_SAMPLE,
        "temperature": TEMPERATURE,
        "pad_token_id": tokenizer.pad_token_id,
        "eos_token_id": tokenizer.eos_token_id,
    }

    if not DO_SAMPLE:
        gen_kwargs.pop("temperature", None)

    out = model.generate(**enc, **gen_kwargs)
    new_tokens = out[0, enc["input_ids"].shape[1]:]
    ans = tokenizer.decode(new_tokens, skip_special_tokens=True)
    return ans.strip()


def evaluate_visibility(answer_df):
    scored = []
    for _, row in answer_df.iterrows():
        d = row.to_dict()
        d.update(score_answer(d))
        scored.append(d)
    scored_df = pd.DataFrame(scored)

    # Dimension score per state.
    dim_summary = (
        scored_df
        .groupby(["model_key", "state_id", "state_rank", "state_name", "dimension"], as_index=False)
        .agg(
            dimension_score=("rubric_score", "mean"),
            marker_score=("marker_score", "mean"),
            word_count=("word_count", "mean"),
            n=("rubric_score", "size"),
        )
    )

    rows = []
    for (model_key, state_id, state_rank, state_name), sub in dim_summary.groupby(["model_key", "state_id", "state_rank", "state_name"]):
        score_by_dim = {r["dimension"]: safe_float(r["dimension_score"]) for _, r in sub.iterrows()}
        v = 0.0
        for dim, w in DIM_WEIGHTS.items():
            v += w * score_by_dim.get(dim, 0.0)
        row = {
            "model_key": model_key,
            "state_id": state_id,
            "state_rank": int(state_rank),
            "state_name": state_name,
            "V_total": float(v),
        }
        for dim in DIM_WEIGHTS:
            row[f"V_{dim}"] = score_by_dim.get(dim, np.nan)
        rows.append(row)

    visibility = pd.DataFrame(rows).sort_values(["model_key", "state_rank"])

    verdicts = []
    for model_key, sub in visibility.groupby("model_key"):
        sub = sub.sort_values("state_rank")
        vals = sub["V_total"].values.astype(float)
        diffs = np.diff(vals)

        strict_mono = bool(np.all(diffs > 0))
        nondecreasing = bool(np.all(diffs >= -1e-9))
        spearman = np.nan
        pearson = np.nan
        if len(vals) >= 2 and np.std(vals) > 1e-12:
            ranks = sub["state_rank"].values.astype(float)
            pearson = float(np.corrcoef(ranks, vals)[0, 1])
            order_vals = pd.Series(vals).rank().values
            spearman = float(np.corrcoef(ranks, order_vals)[0, 1])

        dim_mono = {}
        for dim in DIM_WEIGHTS:
            dvals = sub[f"V_{dim}"].values.astype(float)
            if len(dvals) >= 2:
                dim_mono[dim] = bool(np.all(np.diff(dvals) >= -1e-9))
            else:
                dim_mono[dim] = False

        if strict_mono and pearson >= 0.90:
            verdict = "PASS_STRONG_VISIBILITY_GRADIENT"
        elif nondecreasing and pearson >= 0.80:
            verdict = "PASS_VISIBILITY_GRADIENT"
        elif pearson >= 0.60:
            verdict = "PARTIAL_VISIBILITY_GRADIENT"
        else:
            verdict = "FAIL_VISIBILITY_GRADIENT"

        verdicts.append({
            "model_key": model_key,
            "verdict": verdict,
            "strict_monotonic": strict_mono,
            "nondecreasing": nondecreasing,
            "pearson_state_V": pearson,
            "spearman_state_V": spearman,
            "V_S0": safe_float(sub[sub["state_id"] == "S0"]["V_total"].iloc[0]) if (sub["state_id"] == "S0").any() else np.nan,
            "V_S1": safe_float(sub[sub["state_id"] == "S1"]["V_total"].iloc[0]) if (sub["state_id"] == "S1").any() else np.nan,
            "V_S2": safe_float(sub[sub["state_id"] == "S2"]["V_total"].iloc[0]) if (sub["state_id"] == "S2").any() else np.nan,
            "V_S3": safe_float(sub[sub["state_id"] == "S3"]["V_total"].iloc[0]) if (sub["state_id"] == "S3").any() else np.nan,
            "V_S4": safe_float(sub[sub["state_id"] == "S4"]["V_total"].iloc[0]) if (sub["state_id"] == "S4").any() else np.nan,
            "diffs": ";".join([f"{x:.6f}" for x in diffs]),
            "dim_monotonic_json": json.dumps(dim_mono, ensure_ascii=False),
        })

    verdict_df = pd.DataFrame(verdicts)

    return scored_df, dim_summary, visibility, verdict_df


def run_one_model(model_key, dataset):
    spec = MODEL_SPECS[model_key]
    model_out = OUT_DIR / model_key
    model_out.mkdir(parents=True, exist_ok=True)

    info = {
        "experiment_id": EXPERIMENT_ID,
        "model_key": model_key,
        "model_name": spec["model_name"],
        "path": spec["path"],
        "exists": os.path.exists(spec["path"]),
        "status": "pending",
        "started_at": now_time(),
    }

    if not os.path.exists(spec["path"]):
        info.update({
            "status": "missing_path",
            "error": f"Path not found: {spec['path']}",
        })
        return info

    model = None
    try:
        t0 = time.time()
        model, tokenizer = load_model_and_tokenizer(spec["path"], spec.get("trust_remote_code", True))

        rows = []
        errors = []

        for i, row in dataset.iterrows():
            if i % 10 == 0:
                print(f"[{model_key}] generating row {i}/{len(dataset)}", flush=True)
            try:
                ans = generate_answer(model, tokenizer, row["prompt"])
                rows.append({
                    **row.to_dict(),
                    "model_key": model_key,
                    "model_name": spec["model_name"],
                    "answer_text": ans,
                })
            except Exception as e:
                errors.append({
                    "row_id": int(row["row_id"]),
                    "state_id": row["state_id"],
                    "task_id": row["task_id"],
                    "error_type": type(e).__name__,
                    "error": str(e),
                    "traceback": traceback.format_exc(),
                })
                print(f"[warn][{model_key}] row {row['row_id']} failed: {type(e).__name__}: {e}", flush=True)

        answer_df = pd.DataFrame(rows)
        error_df = pd.DataFrame(errors)

        answer_df.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_answers.csv", index=False, encoding="utf-8-sig")
        error_df.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_errors.csv", index=False, encoding="utf-8-sig")

        if answer_df.empty:
            info.update({
                "status": "empty_answers",
                "n_errors": int(len(error_df)),
            })
            return info

        scored_df, dim_summary, visibility, verdict_df = evaluate_visibility(answer_df)

        scored_df.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_scored_answers.csv", index=False, encoding="utf-8-sig")
        dim_summary.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_dimension_summary.csv", index=False, encoding="utf-8-sig")
        visibility.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_visibility_summary.csv", index=False, encoding="utf-8-sig")
        verdict_df.to_csv(model_out / f"{EXPERIMENT_ID}_{model_key}_verdict_summary.csv", index=False, encoding="utf-8-sig")

        verdict = verdict_df.iloc[0].to_dict() if len(verdict_df) else {}
        info.update({
            "status": "done",
            "finished_at": now_time(),
            "runtime_sec": time.time() - t0,
            "n_rows": int(len(answer_df)),
            "n_errors": int(len(error_df)),
            "verdict": verdict.get("verdict", "UNDETERMINED"),
            "metrics": verdict,
            "outputs": {
                "answers": str(model_out / f"{EXPERIMENT_ID}_{model_key}_answers.csv"),
                "scored_answers": str(model_out / f"{EXPERIMENT_ID}_{model_key}_scored_answers.csv"),
                "dimension_summary": str(model_out / f"{EXPERIMENT_ID}_{model_key}_dimension_summary.csv"),
                "visibility_summary": str(model_out / f"{EXPERIMENT_ID}_{model_key}_visibility_summary.csv"),
                "verdict_summary": str(model_out / f"{EXPERIMENT_ID}_{model_key}_verdict_summary.csv"),
            },
        })

        with open(model_out / f"{EXPERIMENT_ID}_{model_key}_verdict.json", "w", encoding="utf-8") as f:
            json.dump(info, f, ensure_ascii=False, indent=2)

    except Exception as e:
        info.update({
            "status": "failed",
            "finished_at": now_time(),
            "error_type": type(e).__name__,
            "error": str(e),
            "traceback": traceback.format_exc(),
        })

    finally:
        try:
            del model
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
        except Exception:
            pass

    return info


