def find_nearest_exemplars(features: pd.DataFrame, member_residuals: pd.DataFrame, cfg: CFG):
    """
    Prefer SEM-3C.0b residual output if available:
        residual_cos_to_center
    For each family and block, choose max residual_cos_to_center / min residual_l2.
    Main block defaults to center_pca.

    Returns one row per family for nearest exemplar.
    """
    mr = member_residuals.copy()
    if "block" in mr.columns:
        mr = mr[mr["block"] == cfg.MAIN_BLOCK]
    if len(mr) == 0:
        raise ValueError("No member residuals for main block.")

    rows = []
    for fam, g in mr.groupby("seed_family"):
        if "residual_cos_to_center" in g.columns:
            best = g.sort_values("residual_cos_to_center", ascending=False).iloc[0]
        else:
            best = g.sort_values("residual_l2", ascending=True).iloc[0]
        rows.append({
            "seed_family": fam,
            "source_row_id": int(best["row_id"]),
            "nearest_exemplar_prompt": best["prompt"],
            "nearest_exemplar_surface_id": int(best.get("surface_id", -999)),
            "nearest_exemplar_cos_to_center": float(best.get("residual_cos_to_center", np.nan)),
            "nearest_exemplar_l2_to_center": float(best.get("residual_l2", np.nan)),
        })
    return pd.DataFrame(rows)


def build_candidate_dataset(dataset: pd.DataFrame, promptstars: pd.DataFrame, nearest: pd.DataFrame):
    """
    Candidate types:
      - promptstar_natural/structured/compressed from 3C0b
      - nearest_exemplar
      - nearest_plus_structure
      - canonical_minimal_seed
    """
    rows = []
    row_id = 0

    # Prompt* from 3C0b.
    for _, r in promptstars.iterrows():
        rows.append({
            "row_id": row_id,
            "row_type": "candidate",
            "candidate_type": f"promptstar_{r['template_type']}",
            "source_template_type": r["template_type"],
            "seed_family": r["seed_family"],
            "concept_star": r.get("concept_star", ""),
            "operator_id": r.get("operator_id", ""),
            "common_structure": r.get("common_structure", ""),
            "source_row_id": -1,
            "prompt": r["prompt_star_candidate"],
        })
        row_id += 1

    # Nearest exemplar and nearest+structure.
    for _, r in nearest.iterrows():
        fam = r["seed_family"]
        ps_rows = promptstars[promptstars["seed_family"] == fam]
        # Use first natural row to get concept/operator/common.
        ps0 = ps_rows.iloc[0] if len(ps_rows) else {}
        common = ps0.get("common_structure", "")
        concept = ps0.get("concept_star", fam)
        operator = ps0.get("operator_id", "")
        nearest_prompt = r["nearest_exemplar_prompt"]

        rows.append({
            "row_id": row_id,
            "row_type": "candidate",
            "candidate_type": "nearest_exemplar",
            "source_template_type": "nearest_exemplar",
            "seed_family": fam,
            "concept_star": concept,
            "operator_id": operator,
            "common_structure": common,
            "source_row_id": int(r["source_row_id"]),
            "prompt": nearest_prompt,
        })
        row_id += 1

        distilled = (
            f"{nearest_prompt}\n\n"
            f"Preserve the shared structure: {common}.\n"
            f"Use operator: {operator}."
        )
        rows.append({
            "row_id": row_id,
            "row_type": "candidate",
            "candidate_type": "nearest_plus_structure",
            "source_template_type": "nearest_plus_structure",
            "seed_family": fam,
            "concept_star": concept,
            "operator_id": operator,
            "common_structure": common,
            "source_row_id": int(r["source_row_id"]),
            "prompt": distilled,
        })
        row_id += 1

    # Canonical minimal seed from SEM-3A.
    canon = dataset[dataset["row_type"] == "canonical_minimal_seed"]
    for _, r in canon.iterrows():
        rows.append({
            "row_id": row_id,
            "row_type": "candidate",
            "candidate_type": "canonical_minimal_seed",
            "source_template_type": "canonical_minimal_seed",
            "seed_family": r["seed_family"],
            "concept_star": r.get("concept_star", ""),
            "operator_id": r.get("operator_star", ""),
            "common_structure": "",
            "source_row_id": int(r["row_id"]),
            "prompt": r["prompt"],
        })
        row_id += 1

    return pd.DataFrame(rows)


