def main():
    set_seed(cfg.RANDOM_SEED)
    outdir = Path(cfg.OUTPUT_DIR)
    ensure_dir(str(outdir))
    json_dump(asdict(cfg), outdir / "sem3b1_config.json")

    dataset, features, promptstars, member_residuals = load_inputs(cfg)
    nearest = find_nearest_exemplars(features, member_residuals, cfg)
    nearest.to_csv(outdir / "sem3b1_nearest_exemplars.csv", index=False, encoding="utf-8-sig")

    candidate_dataset = build_candidate_dataset(dataset, promptstars, nearest)
    candidate_dataset.to_csv(outdir / "sem3b1_candidate_dataset.csv", index=False, encoding="utf-8-sig")

    feat_path = outdir / "sem3b1_candidate_features.csv"
    if cfg.REUSE_CANDIDATE_FEATURES_IF_EXISTS and feat_path.exists():
        print(f"[SEM-3B.1] Reusing candidate features: {feat_path}")
        candidate_features = pd.read_csv(feat_path)
    else:
        model, tokenizer = load_model_and_tokenizer(cfg)
        candidate_features = extract_all_features(candidate_dataset, model, tokenizer, cfg)
        candidate_features.to_csv(feat_path, index=False, encoding="utf-8-sig")

    original_features = features[features["row_type"] == "original_prompt"].copy()

    blocks = ["center_pca", "decision", "mid", "all", "scalar", "transport", "init"]
    pair_rows = []
    for block in blocks:
        print(f"[SEM-3B.1] Comparing block={block}")
        out = compare_candidates(original_features, candidate_features, block)
        if len(out):
            pair_rows.append(out)

    pair_df = pd.concat(pair_rows, ignore_index=True) if pair_rows else pd.DataFrame()
    pair_df.to_csv(outdir / "sem3b1_pairwise_regeneration.csv", index=False, encoding="utf-8-sig")

    strat_df = summarize_pairwise(pair_df) if len(pair_df) else pd.DataFrame()
    strat_df.to_csv(outdir / "sem3b1_strategy_summary.csv", index=False, encoding="utf-8-sig")

    fam_df = family_summary(pair_df) if len(pair_df) else pd.DataFrame()
    fam_df.to_csv(outdir / "sem3b1_family_summary.csv", index=False, encoding="utf-8-sig")

    stats_df = stats_tests(pair_df) if len(pair_df) else pd.DataFrame()
    stats_df.to_csv(outdir / "sem3b1_statistical_tests.csv", index=False, encoding="utf-8-sig")

    summary = build_summary(strat_df)
    json_dump(summary, outdir / "sem3b1_results_summary.json")

    print("=" * 100)
    print("SEM-3B.1: Prompt* Encoding Ablation")
    print("=" * 100)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print("\nOutput files:")
    for p in [
        "sem3b1_config.json",
        "sem3b1_nearest_exemplars.csv",
        "sem3b1_candidate_dataset.csv",
        "sem3b1_candidate_features.csv",
        "sem3b1_pairwise_regeneration.csv",
        "sem3b1_strategy_summary.csv",
        "sem3b1_family_summary.csv",
        "sem3b1_statistical_tests.csv",
        "sem3b1_results_summary.json",
    ]:
        print("  -", outdir / p)


if __name__ == "__main__":
    main()
