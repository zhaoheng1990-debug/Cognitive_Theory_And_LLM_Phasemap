def compare_candidates(original_features: pd.DataFrame, candidate_features: pd.DataFrame, block: str):
    Xo, Xc, cols = align_spaces(original_features, candidate_features, block)
    if Xo is None:
        return pd.DataFrame()

    orig = original_features.reset_index(drop=True)
    cand = candidate_features.reset_index(drop=True)

    cand_by_type_family = {}
    for i, row in cand.iterrows():
        cand_by_type_family[(row["candidate_type"], row["seed_family"])] = i

    all_indices = list(range(len(cand)))

    rows = []
    for oi, row in orig.iterrows():
        if row.get("row_type") != "original_prompt":
            continue
        true_family = row["seed_family"]
        x = Xo[oi]

        for candidate_type in sorted(cand["candidate_type"].unique()):
            key = (candidate_type, true_family)
            if key not in cand_by_type_family:
                continue

            same_idx = cand_by_type_family[key]
            xsame = Xc[same_idx]
            same_cos = cosine_np(x, xsame)
            same_l2 = float(np.linalg.norm(x - xsame))

            # Random family candidates of same type.
            rand_idxs = [
                i for i, cr in cand.iterrows()
                if cr["candidate_type"] == candidate_type and cr["seed_family"] != true_family
            ]
            if rand_idxs:
                rand_cos = np.array([cosine_np(x, Xc[i]) for i in rand_idxs])
                rand_l2 = np.array([np.linalg.norm(x - Xc[i]) for i in rand_idxs])
                rand_mean_cos = float(np.mean(rand_cos))
                rand_max_cos = float(np.max(rand_cos))
                rand_mean_l2 = float(np.mean(rand_l2))
                rand_min_l2 = float(np.min(rand_l2))
            else:
                rand_mean_cos = rand_max_cos = rand_mean_l2 = rand_min_l2 = np.nan

            # Nearest candidate among this type.
            type_idxs = [i for i, cr in cand.iterrows() if cr["candidate_type"] == candidate_type]
            type_cos = np.array([cosine_np(x, Xc[i]) for i in type_idxs])
            nn_local_idx = int(np.argmax(type_cos))
            nn_idx = type_idxs[nn_local_idx]
            nn_family = cand.iloc[nn_idx]["seed_family"]

            rows.append({
                "row_id": int(row["row_id"]),
                "block": block,
                "candidate_type": candidate_type,
                "true_family": true_family,
                "original_prompt": row["prompt"],
                "candidate_prompt": cand.iloc[same_idx]["prompt"],
                "candidate_source_row_id": int(cand.iloc[same_idx].get("source_row_id", -1)),
                "same_family_cos": same_cos,
                "same_family_l2": same_l2,
                "random_family_mean_cos": rand_mean_cos,
                "random_family_max_cos": rand_max_cos,
                "random_family_mean_l2": rand_mean_l2,
                "random_family_min_l2": rand_min_l2,
                "cos_margin_vs_random_mean": same_cos - rand_mean_cos if np.isfinite(rand_mean_cos) else np.nan,
                "cos_margin_vs_random_max": same_cos - rand_max_cos if np.isfinite(rand_max_cos) else np.nan,
                "l2_gain_vs_random_mean": rand_mean_l2 - same_l2 if np.isfinite(rand_mean_l2) else np.nan,
                "l2_gain_vs_random_min": rand_min_l2 - same_l2 if np.isfinite(rand_min_l2) else np.nan,
                "nearest_same_type_family": nn_family,
                "nearest_same_type_correct_family": int(nn_family == true_family),
                "n_features": len(cols),
            })

    return pd.DataFrame(rows)


def summarize_pairwise(pair_df: pd.DataFrame):
    rows = []
    for (block, ctype), g in pair_df.groupby(["block", "candidate_type"]):
        rows.append({
            "block": block,
            "candidate_type": ctype,
            "n": int(len(g)),
            "mean_same_family_cos": float(g["same_family_cos"].mean()),
            "mean_random_family_mean_cos": float(g["random_family_mean_cos"].mean()),
            "mean_cos_margin_vs_random_mean": float(g["cos_margin_vs_random_mean"].mean()),
            "frac_cos_gt_random_mean": float((g["cos_margin_vs_random_mean"] > 0).mean()),
            "frac_cos_gt_random_max": float((g["cos_margin_vs_random_max"] > 0).mean()),
            "mean_same_family_l2": float(g["same_family_l2"].mean()),
            "mean_l2_gain_vs_random_mean": float(g["l2_gain_vs_random_mean"].mean()),
            "frac_l2_better_than_random_mean": float((g["l2_gain_vs_random_mean"] > 0).mean()),
            "nearest_same_type_correct_family_rate": float(g["nearest_same_type_correct_family"].mean()),
        })
    return pd.DataFrame(rows)


def family_summary(pair_df: pd.DataFrame):
    rows = []
    for (block, ctype, fam), g in pair_df.groupby(["block", "candidate_type", "true_family"]):
        rows.append({
            "block": block,
            "candidate_type": ctype,
            "seed_family": fam,
            "n": int(len(g)),
            "mean_cos_margin_vs_random_mean": float(g["cos_margin_vs_random_mean"].mean()),
            "frac_cos_gt_random_mean": float((g["cos_margin_vs_random_mean"] > 0).mean()),
            "mean_l2_gain_vs_random_mean": float(g["l2_gain_vs_random_mean"].mean()),
            "nearest_same_type_correct_family_rate": float(g["nearest_same_type_correct_family"].mean()),
        })
    return pd.DataFrame(rows)


def stats_tests(pair_df: pd.DataFrame):
    rows = []
    for (block, ctype), g in pair_df.groupby(["block", "candidate_type"]):
        cos_same = g["same_family_cos"].values
        cos_rand = g["random_family_mean_cos"].values
        l2_same = g["same_family_l2"].values
        l2_rand = g["random_family_mean_l2"].values

        try:
            tt = ttest_rel(cos_same, cos_rand, nan_policy="omit")
            t_stat, t_p = float(tt.statistic), float(tt.pvalue)
        except Exception:
            t_stat, t_p = np.nan, np.nan
        try:
            ww = wilcoxon(cos_same - cos_rand)
            w_stat, w_p = float(ww.statistic), float(ww.pvalue)
        except Exception:
            w_stat, w_p = np.nan, np.nan

        try:
            tt2 = ttest_rel(l2_rand, l2_same, nan_policy="omit")
            t2_stat, t2_p = float(tt2.statistic), float(tt2.pvalue)
        except Exception:
            t2_stat, t2_p = np.nan, np.nan

        rows.append({
            "block": block,
            "candidate_type": ctype,
            "n": int(len(g)),
            "cos_margin_mean": float(np.nanmean(cos_same - cos_rand)),
            "cos_paired_t_stat": t_stat,
            "cos_paired_t_p": t_p,
            "cos_wilcoxon_stat": w_stat,
            "cos_wilcoxon_p": w_p,
            "l2_gain_mean": float(np.nanmean(l2_rand - l2_same)),
            "l2_paired_t_stat": t2_stat,
            "l2_paired_t_p": t2_p,
        })

    return pd.DataFrame(rows)


def build_summary(strategy_df: pd.DataFrame):
    summary = {
        "config": asdict(cfg),
        "verdict": "UNDETERMINED",
        "main_block": cfg.MAIN_BLOCK,
        "best_overall": {},
        "best_main_block": {},
        "diagnosis": "",
        "interpretation": [],
    }

    if len(strategy_df):
        df = strategy_df.copy()
        df["score"] = (
            df["mean_cos_margin_vs_random_mean"].fillna(-999)
            + df["frac_cos_gt_random_mean"].fillna(0)
            + df["nearest_same_type_correct_family_rate"].fillna(0)
            + 0.1 * df["mean_l2_gain_vs_random_mean"].fillna(0)
        )
        best = df.sort_values("score", ascending=False).iloc[0].to_dict()
        summary["best_overall"] = best

        main = df[df["block"] == cfg.MAIN_BLOCK]
        if len(main):
            main_best = main.sort_values("score", ascending=False).iloc[0].to_dict()
            summary["best_main_block"] = main_best
        else:
            main_best = best

        # Check diagnostic comparisons.
        def get(block, ctype, field):
            sub = df[(df["block"] == block) & (df["candidate_type"] == ctype)]
            if len(sub):
                return float(sub.iloc[0].get(field, np.nan))
            return np.nan

        main_block = cfg.MAIN_BLOCK
        nearest_margin = get(main_block, "nearest_exemplar", "mean_cos_margin_vs_random_mean")
        natural_margin = get(main_block, "promptstar_natural_prompt_star", "mean_cos_margin_vs_random_mean")
        distilled_margin = get(main_block, "nearest_plus_structure", "mean_cos_margin_vs_random_mean")
        canonical_margin = get(main_block, "canonical_minimal_seed", "mean_cos_margin_vs_random_mean")

        if np.isfinite(nearest_margin) and nearest_margin > natural_margin and nearest_margin > canonical_margin:
            summary["diagnosis"] = "LANGUAGE_TEMPLATE_BOTTLENECK_NEAREST_EXEMPLAR_BETTER"
        elif np.isfinite(distilled_margin) and distilled_margin > nearest_margin and distilled_margin > natural_margin:
            summary["diagnosis"] = "EXEMPLAR_PLUS_STRUCTURE_BEST"
        elif np.isfinite(canonical_margin) and canonical_margin >= max(natural_margin, nearest_margin, distilled_margin):
            summary["diagnosis"] = "CANONICAL_REMAINS_BEST"
        else:
            summary["diagnosis"] = "NO_CLEAR_ENCODING_WINNER"

        mb = summary.get("best_main_block", {})
        margin = mb.get("mean_cos_margin_vs_random_mean", -999)
        frac = mb.get("frac_cos_gt_random_mean", 0)
        nn = mb.get("nearest_same_type_correct_family_rate", 0)
        l2_gain = mb.get("mean_l2_gain_vs_random_mean", -999)

        if margin > 0 and frac >= 0.85 and nn >= 0.70 and l2_gain > 0:
            summary["verdict"] = "PASS_STRONG_PROMPT_ENCODING"
        elif margin > 0 and frac >= 0.70 and nn >= 0.50:
            summary["verdict"] = "PASS_LITE_PROMPT_ENCODING"
        elif margin > 0 and frac >= 0.60:
            summary["verdict"] = "PARTIAL_PASS_PROMPT_ENCODING_SIGNAL"
        else:
            summary["verdict"] = "NO_PASS_YET"

    summary["interpretation"] = [
        "If nearest_exemplar beats generated Prompt*, the family center is real but current language template is weak.",
        "If nearest_plus_structure beats nearest_exemplar, adding distilled common structure helps encode μ_F.",
        "If all candidates fail, μ_F may be a statistical center not realizable by a single prompt, or feature spaces are misaligned.",
        "If Prompt* candidates pass, SEM-3B regeneration can proceed with that encoding strategy.",
    ]
    return summary


